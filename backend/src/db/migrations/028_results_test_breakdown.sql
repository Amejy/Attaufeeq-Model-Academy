ALTER TABLE results
  ADD COLUMN IF NOT EXISTS test1 NUMERIC(6,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS test2 NUMERIC(6,2) NOT NULL DEFAULT 0;

UPDATE results
SET test1 = ROUND(COALESCE(ca, 0) / 2.0, 2),
    test2 = COALESCE(ca, 0) - ROUND(COALESCE(ca, 0) / 2.0, 2)
WHERE COALESCE(test1, 0) = 0
  AND COALESCE(test2, 0) = 0
  AND COALESCE(ca, 0) > 0;
